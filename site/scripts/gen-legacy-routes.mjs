#!/usr/bin/env node
/**
 * 从 web/src/App.tsx 生成 Go 侧的「旧 SPA 路由表」。
 *
 * 为什么需要：自托管同域方案里根路径 `/` 变成官网，应用搬到 `/app/`。为了不废掉
 * 既有外链（`/stock/000519`、`/news` 等），服务端要把这些历史路径 302 到 `/app/<原路径>`。
 * 路由清单必须跟 `App.tsx` 同源，所以生成到 Go 源码里（运行时零依赖），而不是手写枚举。
 *
 * 产物：internal/serverapp/legacy_routes_generated.go（提交进仓库）
 * 用法：node scripts/gen-legacy-routes.mjs [--check]
 *   --check  只比对不写盘，供 `make site-check` 与 CI 用
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseRoutes } from './gen-pages-404.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(HERE, '..');
const ROOT = resolve(SITE, '..');

const ROUTES_FILE = resolve(ROOT, 'web/src/App.tsx');
const OUT = resolve(ROOT, 'internal/serverapp/legacy_routes_generated.go');
const CHECK = process.argv.includes('--check');

const rel = (p) => relative(ROOT, p);

function render(routes) {
  const lines = [];
  lines.push('// Code generated by site/scripts/gen-legacy-routes.mjs from web/src/App.tsx; DO NOT EDIT.');
  lines.push('');
  lines.push('package serverapp');
  lines.push('');
  lines.push('// legacySPARoutes 是应用搬到 /app/ 之前的 SPA 路由清单。');
  lines.push('//');
  lines.push('// 服务端用它把这些历史路径（外链、书签、旧后端渲染的链接）302 到 /app/<原路径>，');
  lines.push('// 从而在不保留旧路由的前提下不废掉旧链接。');
  lines.push('//');
  lines.push('// 重新生成：make site（或 node site/scripts/gen-legacy-routes.mjs）。');
  lines.push('// 路由的权威来源是 web/src/App.tsx，改了路由必须重跑，否则 make site-check 会失败。');
  lines.push('var legacySPARoutes = []string{');
  for (const route of routes) {
    lines.push(`\t${JSON.stringify(route)},`);
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const routes = parseRoutes(readFileSync(ROUTES_FILE, 'utf8'));
  if (!routes.length) {
    console.error(`[gen-legacy-routes] 未能从 ${rel(ROUTES_FILE)} 解析到任何路由`);
    process.exit(1);
  }

  const text = render(routes);

  if (CHECK) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
      console.error(
        `[gen-legacy-routes] ${rel(OUT)} 与 ${rel(ROUTES_FILE)} 不一致，跑 node site/scripts/gen-legacy-routes.mjs 重新生成`,
      );
      process.exit(1);
    }
    console.log(`[gen-legacy-routes] 一致：${routes.length} 条旧 SPA 路由`);
    return;
  }

  writeFileSync(OUT, text);
  console.log(`[gen-legacy-routes] 写入 ${rel(OUT)}（${routes.length} 条旧 SPA 路由）`);
}

main();
